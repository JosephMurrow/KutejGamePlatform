import { classicPosition, type Position } from "../engine/position";

/**
 * Режим 11, «Поддавки» (docs/MODES.md): цель обратная — скормить сопернику
 * своего короля.
 *
 * Держится режим на обязательном взятии: без него соперник просто не станет
 * брать короля. Само взятие — правило позиции (engine/position.ts), поэтому
 * доска в браузере подсвечивает ровно то, что примет сервер.
 */

export function giveawayPosition(): Position {
  return {
    ...classicPosition(),
    // Рокировки нет: король здесь обычная фигура, которую подставляют, и
    // прятать его за ладью незачем.
    castling: [],
    rules: { goal: "feed", mustCapture: true },
  };
}

/** Правила для игрока — на карточке перед стартом и по кнопке у доски. */
export function giveawayRules(): string[] {
  return [
    "Цель обратная: скормить сопернику своего короля. Победил тот, чьего короля съели.",
    "Шаха и мата нет: король — обычная фигура, и подставлять его можно и нужно.",
    "Если есть чем взять — брать обязательно, как в шашках. Взять можно несколькими способами — выбираешь сам.",
    "Не осталось ходов — победа: отдавать больше нечего.",
    "Рокировки нет. Превращение обычное, королём стать нельзя.",
  ];
}
