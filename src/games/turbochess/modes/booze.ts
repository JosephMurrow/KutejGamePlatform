import { classicPosition, type Position } from "../engine/position";

/**
 * Режим 5, «Алко-шахматы» (docs/MODES.md): после каждого взятия потерявший
 * фигуру пьёт, а срубивший это подтверждает.
 *
 * Своего у режима в позиции нет вовсе: окно, его полминуты, счётчик выпитого
 * и штраф за молчание — стык с платформой, и живут они в комнате. Движку
 * достаётся только сам штраф: снять у обоих по случайной фигуре.
 */

/** Сколько ждать подтверждения. Полминуты — так решено в постановке. */
export const TOAST_MS = 30_000;

export function boozePosition(): Position {
  return classicPosition();
}

