import type { PieceKind } from "../engine/pieces";
import { classicPosition, type Position } from "../engine/position";

/**
 * Режим 2, «Подкрепление» (docs/MODES.md): у каждого в запасе по одной фигуре
 * каждого вида, и вывести её на доску — ход.
 *
 * Своего в режиме только начальный запас: само выставление — общая механика
 * резерва, она в движке (engine/moves.ts) и её же делит с зомби.
 */

/** Запас: по одной фигуре каждого вида, кроме короля. Порядок — по старшинству. */
export const REINFORCEMENT_KINDS: readonly PieceKind[] = [
  "q",
  "r",
  "b",
  "n",
  "p",
];

export function reinforcementsPosition(): Position {
  return {
    ...classicPosition(),
    reserve: [[...REINFORCEMENT_KINDS], [...REINFORCEMENT_KINDS]],
  };
}

/** Правила для игрока — на карточке перед стартом и по кнопке у доски. */
export function reinforcementsRules(): string[] {
  return [
    "Расстановка и ходы обычные. Сверх них у каждого запас: ферзь, ладья, слон, конь и пешка — по одной.",
    "В свой ход вместо хода фигурой можно вызвать подкрепление: поставить фигуру из запаса на свободную клетку своих двух первых горизонталей.",
    "Выставленная фигура работает сразу: может объявить шах и даже мат, может закрыть своего короля от шаха.",
    "Пешку на первую горизонталь не ставят. Запас соперника виден — это открытая информация.",
  ];
}
