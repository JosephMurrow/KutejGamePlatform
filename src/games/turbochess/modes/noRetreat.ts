export function noRetreatRules(): string[] {
  return [
    "Фигуры ходят только вперёд и вбок. Назад — никогда: прошёл горизонталь, дороги назад нет.",
    "Ладья ходит вперёд и вбок, слон — по двум передним диагоналям, конь — четырьмя ходами из восьми, ферзь и король — по пяти направлениям из восьми. Пешка как обычно.",
    "Ходить нечем — поражение, а не пат. Мат, шах и превращение работают как в обычных шахматах.",
    "Рокировки нет: это отход короля в укрытие, а пацаны не прячутся.",
    "Всё, что позади выбранной фигуры, затемняется: видно, куда ей уже нельзя.",
  ];
}
