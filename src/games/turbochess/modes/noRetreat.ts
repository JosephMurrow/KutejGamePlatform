import {
  CLASSIC_RULES,
  classicPosition,
  type Position,
} from "../engine/position";

/**
 * Режим 6, «Пацанские шахматы» (docs/MODES.md): фигуры ходят только вперёд и
 * вбок, назад — никогда.
 *
 * Своего у режима два правила в позиции, и оба общие для всей таблицы ходов:
 * направления назад отсекаются у каждой фигуры разом, а «ходить нечем»
 * становится поражением, а не патом. Помнить пройденные горизонтали не надо:
 * раз назад ходов нет, вернуться фигура не может в принципе.
 */

export function noRetreatPosition(): Position {
  return {
    ...classicPosition(),
    // Рокировки нет: это отход короля в укрытие, а пацаны не прячутся.
    castling: [],
    rules: { ...CLASSIC_RULES, forwardOnly: true, stalemate: "loss" },
  };
}

