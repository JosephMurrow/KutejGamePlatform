import {
  CLASSIC_RULES,
  classicPosition,
  type Position,
} from "../engine/position";

/**
 * Режим 15, «Анархия в Соединённом Королевстве» (docs/MODES.md): любой ход
 * соперника отменяется большой красной кнопкой «НЕТ».
 *
 * Своего у режима два: счётчик «НЕТ» в позиции — по четыре на сторону — и
 * правило «мат не кончает партию, пока есть чем сказать нет». Сам откат умеет
 * движок: он же держит запрет на повтор отменённого хода.
 */

/** Сколько раз за партию можно сказать «НЕТ». */
export const VETOES = 4;

export function anarchyPosition(): Position {
  return {
    ...classicPosition(),
    rules: { ...CLASSIC_RULES, anarchy: true },
    vetoes: [VETOES, VETOES],
  };
}

/** Правила для игрока — на карточке перед стартом и по кнопке у доски. */
export function anarchyRules(): string[] {
  return [
    `Шахматы обычные, но любой ход соперника можно отменить кнопкой «НЕТ». ${VETOES} раза за партию: лампочки у кнопки показывают, сколько осталось.`,
    "Отменённый ход не переигрывается: соперник ходит снова и обязан сделать другой ход. Другой — значит другой, той же фигурой можно.",
    "Два «НЕТ» подряд на один ход не бывает: отменить можно только новый ход соперника.",
    "Отменённый ход возвращает сопернику потраченное на него время — иначе кнопка была бы способом сжечь чужие часы.",
    "Мат тоже не приговор, пока есть чем сказать «НЕТ»: отменяйте и играйте дальше.",
  ];
}
