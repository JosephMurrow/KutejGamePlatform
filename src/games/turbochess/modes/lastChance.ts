import { inCheck } from "../engine/moves";
import type { Side } from "../engine/pieces";
import {
  CLASSIC_RULES,
  classicPosition,
  type Position,
} from "../engine/position";

/**
 * Режим 7, «Последний шанс» (docs/MODES.md): под шахом у игрока появляется
 * кнопка «ПОПРОБЫВАТЬ НЕ УМЕРЕТЬ» — король прыгает в случайную свободную
 * клетку, и ход переходит сопернику.
 *
 * Своего у режима два: правило «мат не кончает партию, пока шанс цел» и сами
 * шансы, по одному на сторону. Прыжок делает движок, а куда — решает бросок
 * комнаты по зерну партии.
 */

/** Сколько шансов на партию. Один — так решено в постановке. */
export const CHANCES = 1;

export function lastChancePosition(): Position {
  return {
    ...classicPosition(),
    rules: { ...CLASSIC_RULES, lastChance: true },
    chances: [CHANCES, CHANCES],
  };
}

/** Есть ли прямо сейчас на что жать: шах и неистраченный шанс. */
export function chanceReady(position: Position, side: Side): boolean {
  if ((position.chances[side] ?? 0) <= 0) return false;
  return position.turn === side && inCheck(position, side);
}

