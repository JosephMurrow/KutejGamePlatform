import type { PieceKind } from "../engine/pieces";
import {
  CLASSIC_RULES,
  classicPosition,
  type Position,
} from "../engine/position";

/**
 * Режим 4, «Мега-шахматы» (docs/MODES.md): фигура, дошедшая до первой
 * горизонтали соперника, получает особые свойства и остаётся собой.
 *
 * Своего у режима одно правило в позиции: мега-формы ставит движок, когда
 * фигура доходит, а как они ходят — таблица `MEGA_PATTERNS` (engine/pieces.ts).
 * Король мега-формы не получает: дойдя, он просто выигрывает.
 */

export function megaPosition(): Position {
  return {
    ...classicPosition(),
    rules: { ...CLASSIC_RULES, mega: true },
  };
}

/** Как зовётся мега-форма — для подсказки у доски. */
export const MEGA_NAME: Record<PieceKind, string> = {
  p: "мега-пешка",
  n: "мега-конь",
  b: "мега-слон",
  r: "пушка",
  q: "амазонка",
  k: "король",
};

