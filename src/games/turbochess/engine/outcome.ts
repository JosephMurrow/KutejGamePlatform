import type { Side } from "./pieces";

/**
 * Чем кончилась партия.
 *
 * Отдельно от правил, потому что причину знают все: движок её ставит, комната
 * рассылает, экран показывает человеческим текстом. К шахматным причинам
 * добавляются причины режимов; «король дошёл до трона» придёт со своим
 * режимом (docs/MODES.md, режим 4).
 *
 * В базе причина лежит строкой, а не перечислением
 * (prisma/schema/turbochess.prisma): новая причина миграции не требует.
 */

/** Кто выиграл: номер стороны или ничья. */
export type Result = Side | "draw";

/**
 * Почему партия кончилась.
 *
 * Троекратное повторение и пятьдесят ходов по правилам — право заявить, а не
 * автомат; пятикратное и семьдесят пять — автомат (docs/SPEC.md, раздел 4).
 */
export type EndReason =
  | "checkmate"
  | "stalemate"
  | "resign"
  | "flag"
  | "insufficient"
  /** Флаг у одного, но у другого нечем матовать: по правилам — ничья. */
  | "flagVsInsufficient"
  | "threefold"
  | "fivefold"
  | "fiftyMoves"
  | "seventyFiveMoves"
  | "agreement"
  | "abandoned"
  /** Разошлись до первого хода: партии как будто и не было. */
  | "aborted"
  /** Предохранитель: слишком много ходов или слишком долго. */
  | "tooLong"
  /** «На уничтожение»: у соперника не осталось ни одной фигуры. */
  | "wiped"
  /**
   * «На уничтожение»: партия остановлена и посчитана по взятым фигурам —
   * ходить нечем или полсотни полуходов никто никого не съел.
   */
  | "counted"
  /** «Поддавки»: короля съели — его хозяин и выиграл. */
  | "kingTaken"
  /** «Поддавки»: ходов не осталось — отдавать больше нечего, это победа. */
  | "noMoves"
  /** «Ядерные»: заряд набран и бомба сброшена. */
  | "nuke"
  /** «Мега-шахматы»: король дошёл до трона соперника. */
  | "throne";

export interface Outcome {
  result: Result;
  reason: EndReason;
}

