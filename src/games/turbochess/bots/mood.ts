import type { BaseMoment } from "./moments";

/**
 * Настроение бота: оценка позиции плюс то, что случилось последним ходом.
 *
 * Заведено ради одного правила, сказанного хозяином: бот, теряющий ферзя, не
 * хвастается. Момент говорит, о чём речь, а настроение — с каким лицом, и
 * поэтому у настроения есть свои моменты: злорадство, нытьё, паника, кураж. Они
 * звучат тогда, когда сказать больше нечего — ход был обычный, а молчать всю
 * партию бот не должен.
 */

export type Mood = "gloat" | "whine" | "panic" | "swagger";

/** Насколько надо вести, чтобы начать злорадствовать: полторы пешки. */
const AHEAD = 150;

/** Насколько надо отставать, чтобы заныть. */
const BEHIND = -150;

/** Отставание, на котором начинается паника: ферзь. */
const LOST = -600;

/**
 * Настроение по положению дел.
 *
 * `edge` — оценка позиции глазами бота, `swing` — насколько она изменилась с
 * его прошлого хода. Резкая перемена важнее самой позиции: проигрывающий, но
 * только что отыгравший фигуру, звучит бодрее, чем выигрывающий, который её
 * зевнул.
 */
export function moodOf(edge: number, swing: number): Mood {
  if (edge <= LOST) return "panic";
  if (swing <= BEHIND) return edge > AHEAD ? "swagger" : "whine";
  if (swing >= AHEAD) return "gloat";
  if (edge >= AHEAD) return "gloat";
  if (edge <= BEHIND) return "whine";

  return "swagger";
}

/** Настроение — это тоже момент: колоды у них общие. */
export function moodMoment(mood: Mood): BaseMoment {
  return mood;
}
