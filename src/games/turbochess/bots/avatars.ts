/**
 * Служебные номера аватаров ботов турбо-шахмат.
 *
 * У платитутки занято 1000–1011, шахматы держат с 1100; турбо-шахматы берут с
 * 1200, между наборами оставлен зазор на рост соседей. Номер закрепляется уже
 * сейчас, хотя лиц ещё нет: диапазон должен быть занят до того, как за него
 * сядет следующая игра.
 */

/** Первый номер, отданный турбо-шахматам. */
export const BOT_AVATAR_OFFSET = 1200;

/**
 * Пока ни одного: соперник-программа появится на этапе 11 (docs/PLAN.md), а
 * лица ботов рисуются и утверждаются отдельно. Ноль означает, что в диапазон
 * пока никто не попадает, и платформа за картинкой не пойдёт.
 */
export const BOT_COUNT = 0;

const DIR = "/games/turbochess/bots";

/** Адрес картинки бота по служебному номеру аватара. */
export function botAvatarSrc(avatarId: number): string {
  const index = Math.max(0, avatarId - BOT_AVATAR_OFFSET);
  return `${DIR}/${String(index).padStart(2, "0")}.svg`;
}
