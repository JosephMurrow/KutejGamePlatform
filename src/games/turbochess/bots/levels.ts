/**
 * Уровни соперника-программы.
 *
 * Четыре, и сила режется **глубиной перебора и вероятностью зевка**. Узлов, как
 * у шахмат, здесь нет: там силу резал штатной ручкой Стокфиш, а у нас свой
 * перебор, и единственная честная ручка у него — глубина (docs/BACKLOG.md E3).
 *
 * Бюджет просмотра — не ручка силы, а предохранитель: доска 16×16 на четверых
 * даёт сотни ходов в узле, и без потолка «глубина 3» считалась бы минуту.
 * Поэтому глубина заявленная, а добирается она углублением, пока бюджет цел
 * (см. `search.ts`).
 */

export type LevelId = "easy" | "normal" | "hard" | "expert";

export interface Level {
  id: LevelId;
  /** Как уровень называется человеку. */
  title: string;
  /** На сколько полуходов вперёд смотрит. */
  depth: number;
  /** Доля ходов, в которых бот берёт не лучший вариант. */
  sloppiness: number;
  /**
   * Насколько худший ход допустим при зевке, в сотых долях пешки.
   *
   * Полторы пешки — заметная ошибка, но не «ферзь под пешку»: такое читается
   * как поломка, а не как слабая игра.
   */
  maxLoss: number;
  /** Потолок просмотренных позиций на ход. */
  nodes: number;
  /** Как уровень объясняется человеку в форме. */
  hint: string;
  /**
   * Видит ли бот чужие секреты: заряд бомбы, двойного агента, расстановку под
   * рубашкой.
   *
   * Решено хозяином: зависит от уровня, и на всех, кроме максимального, — нет.
   * Эксперту это преимущество дано вместо скрытого пятого уровня
   * ([BOTS.md](../docs/BOTS.md), А11).
   */
  sees: boolean;
  /**
   * Водит ли альянсы в королевской битве. Тоже только максимальный: сговор
   * троих против одного человека на слабых уровнях превратил бы режим в казнь.
   */
  allies: boolean;
}

