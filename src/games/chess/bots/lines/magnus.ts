/**
 * Магнус. Не характер, а отдельная шутка: он играет на 2900 и вдобавок
 * откровенно жульничает (src/games/chess/docs/BACKLOG.md D3).
 *
 * Реплик на момент меньше, чем у четверых характеров: он один, партий с ним
 * будет немного, а дюжины хватает, чтобы за партию не повториться. Зато у него
 * есть моменты, которых у остальных быть не может, — по одному на каждый приём.
 */

/** Чем именно он жульничает. Каждый приём обязан быть заметен игроку. */
export type Cheat =
  /** Думает дольше своего лимита и сообщает об этом. */
  | "stalling"
  /** Комментирует фигуру, за которую игрок взялся. */
  | "holding"
  /** Один раз за партию откатывает ход игрока. */
  | "takeback"
  /** Передумывает и переигрывает свой ход. */
  | "redo"
  /** Не принимает ничью никогда. */
  | "noDraw"
  /** Объявляет мат в N по таблицам окончаний. */
  | "tablebase"
  /** Его флаг не падает. */
  | "noFlag";

export const CHEATS: Cheat[] = [
  "stalling",
  "holding",
  "takeback",
  "redo",
  "noDraw",
  "tablebase",
  "noFlag",
];

