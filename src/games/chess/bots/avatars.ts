/**
 * Служебные номера аватаров шахматных ботов.
 *
 * У платитутки занято 1000–1011; шахматы берут с 1100, между наборами оставлен
 * зазор на её рост (src/games/chess/docs/BACKLOG.md A5). Номер закрепляется уже
 * сейчас, хотя лиц ещё нет: диапазон должен быть занят до того, как за него
 * сядет третья игра.
 */

/** Первый номер, отданный шахматам. */
export const BOT_AVATAR_OFFSET = 1100;

/**
 * Пока ни одного: боты приходят вместе с движком, а их лица рисуются и
 * утверждаются отдельно (src/games/chess/docs/PLAN.md, этапы 7 и 8). Ноль
 * означает, что в диапазон пока никто не попадает, и платформа за картинкой
 * не пойдёт.
 */
export const BOT_COUNT = 0;

const DIR = "/games/chess/bots";

/** Адрес картинки бота по служебному номеру аватара. */
export function botAvatarSrc(avatarId: number): string {
  const index = Math.max(0, avatarId - BOT_AVATAR_OFFSET);
  return `${DIR}/${String(index).padStart(2, "0")}.svg`;
}
