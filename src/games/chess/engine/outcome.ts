/**
 * Чем кончилась партия.
 *
 * Отдельно от правил, потому что причину знают все: движок её ставит, комната
 * рассылает, база хранит, а экран показывает человеческим текстом.
 */

/** Кто выиграл. */
export type ChessResult = "white" | "black" | "draw";

/**
 * Почему партия кончилась.
 *
 * Троекратное повторение и пятьдесят ходов по правилам — право заявить, а не
 * автомат; мы, как и площадки, применяем их сами, но причину называем честно,
 * чтобы игрок понял, что произошло (src/games/chess/docs/BACKLOG.md B4).
 */
export type EndReason =
  /** Мат. */
  | "checkmate"
  /** Пат: ходов нет, а шаха нет. */
  | "stalemate"
  /** Сдался. */
  | "resign"
  /** Не успел с ходом. */
  | "flag"
  /** Ни одной стороне не хватает материала на мат. */
  | "insufficient"
  /**
   * Флаг у одного, но у другого нечем матовать. По правилам это ничья, а не
   * поражение — и это забывают чаще всего остального.
   */
  | "flagVsInsufficient"
  /** Позиция повторилась трижды. */
  | "threefold"
  /** Позиция повторилась пять раз: ничья без всякой заявки. */
  | "fivefold"
  /** Пятьдесят ходов без взятий и ходов пешкой. */
  | "fiftyMoves"
  /** Семьдесят пять ходов: ничья без заявки. */
  | "seventyFiveMoves"
  /** Согласились на ничью. */
  | "agreement"
  /** Ушёл и не вернулся. */
  | "abandoned"
  /** Разошлись до первого хода: партии как будто и не было. */
  | "aborted"
  /**
   * Партия упёрлась в потолок: слишком много ходов или слишком долго.
   *
   * Это не правило шахмат, а предохранитель: лимит на ход ограничивает ход, но
   * не партию, и двое упрямых заняли бы комнату на полдня — а в безлимитной
   * приватной навсегда (src/games/chess/docs/BACKLOG.md A2).
   */
  | "tooLong";

export interface Outcome {
  result: ChessResult;
  reason: EndReason;
}

