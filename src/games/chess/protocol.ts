import type { PlayerPayload, RoomStatePayload } from "@/shared/protocol";
import type { TimeControl, ViewerDelay } from "./rooms/settings";

/**
 * Протокол шахмат: всё, что платформа про игру знать не обязана — сторона,
 * позиция, ход, исход партии.
 *
 * Типы расширяют платформенные, а не заворачиваются в них: снимок на проводе
 * остаётся плоским (docs/BACKLOG.md A3).
 */

/** Код игры: им она зовётся в адресах, в базе и в реестрах. */
export const GAME_ID = "chess";

/**
 * Ключ общего зала. Собственный, а не «global» — тот навсегда закреплён за
 * платитуткой, за ним её живые раунды и очки (docs/README.md).
 */
export const GLOBAL_ROOM = "chess-lobby";

/**
 * Партия сыграна в общем зале.
 *
 * Досок в зале много, и у каждой свой ключ — ключ зала с приставленным
 * идентификатором доски. Рейтинг зала считается только по таким партиям:
 * приватные в него не попадают вовсе (src/games/chess/docs/BACKLOG.md E3).
 */
export function inLobby(roomKey: string): boolean {
  return roomKey === GLOBAL_ROOM || roomKey.startsWith(`${GLOBAL_ROOM}:`);
}

/**
 * Действия, которые понимает движок шахмат.
 *
 * Предложение ничьей сопернику и реванш появятся со своими экранами; премув —
 * в этапе 12 (src/games/chess/docs/PLAN.md). Заводить имена под нереализованное
 * незачем: платформа регистрирует их в сокете как есть, и мёртвое действие
 * выглядело бы рабочим.
 */
export const GAME_EVENT = {
  /** Ход: координаты и фигура превращения. Запись партии считает сервер. */
  move: "game:move",
  /** Сдача. */
  resign: "game:resign",
  /**
   * Игрок взялся за фигуру.
   *
   * ⚠️ **Отправляется только в партии с Магнусом и не рассылается никому.** Ни
   * сопернику, ни зрителям, ни на экран. Это ровно то, что режим стримера
   * прячет от всего мира (F1); Магнусу оно отдаётся намеренно — в этом шутка
   * (src/games/chess/docs/BACKLOG.md D3).
   *
   * Одна ошибка здесь — и утечка станет общей. Событие не должно появиться ни
   * в одном снимке, ни в одном событии комнаты.
   */
  holding: "game:holding",
  /**
   * Требование ничьей: по троекратному повторению или пятидесяти ходам. По
   * правилам это право игрока, а не автоматический конец партии
   * (src/games/chess/docs/SPEC.md).
   */
  claimDraw: "game:draw",
  /**
   * Предложить ничью сопернику — или принять его предложение, если оно висит.
   *
   * Одно действие на оба случая намеренно: кнопка у человека одна, и «принять»
   * от «предложить» отличается только тем, кто предложил первым.
   */
  offerDraw: "game:offer",
  /** Отказаться от предложенной ничьей. */
  declineDraw: "game:decline",
  /**
   * Ещё партия. В своей комнате — новая партия с теми же двумя и сменой
   * цветов; в общем зале — встать в очередь заново.
   */
  rematch: "game:rematch",
  /** Уйти из очереди зала, не выходя из него самого. */
  leaveQueue: "game:unqueue",
} as const;

/** Цвет за доской. У зрителя цвета нет. */
export type ChessColor = "white" | "black";

/** Что сейчас происходит в комнате. */
/** Сводка зала: сколько ждёт, сколько партий, сколько народу. */
export interface LobbySummary {
  waiting: number;
  boards: number;
  present: number;
}

export type ChessPhase =
  /** Ждём второго: за доской меньше двоих. */
  | "waiting"
  /** Партия идёт. */
  | "playing"
  /** Партия кончилась — на доске финальная позиция. */
  | "over"
  /** Общий зал: соперник ещё не нашёлся, доски нет. */
  | "queue";

export interface ChessPlayerPayload extends PlayerPayload {
  /** За какой цвет играет. */
  color: ChessColor;
  /** Ушёл, и его ждут: соперник должен это видеть. */
  away: boolean;
  /** Рейтинг общего зала рядом с ником. */
  rating: number;
  /**
   * Рейтинг ещё не устоялся: рисуется с вопросительным знаком. Первый десяток
   * партий система по сути гадает (src/games/chess/docs/BACKLOG.md E1).
   */
  provisional: boolean;
}

export interface ChessStatePayload extends RoomStatePayload<ChessPlayerPayload> {
  phase: ChessPhase;
  /**
   * Позиция в нотации Форсайта — Эдвардса; null, пока партия не началась.
   * Клиент никогда не присылает позицию обратно, только ход
   * (src/games/chess/docs/BACKLOG.md B1).
   */
  fen: string | null;
  /** Чей ход. Вне партии — null. */
  turn: ChessColor | null;
  /** Записи ходов по порядку: из них собирается список партии. */
  moves: string[];
  /** Откуда и куда пошли последний раз: доска это подсвечивает. */
  lastMove: { from: string; to: string } | null;
  /** Есть ли прямо сейчас основание требовать ничью. */
  claimable: "threefold" | "fiftyMoves" | null;
  /**
   * Кто предложил ничью и ждёт ответа; `null` — никто.
   *
   * Зрителям всегда `null`: предложение до ответа — секрет двоих, и от зрителя
   * оно прячется вместе с подсказками (src/games/chess/docs/BACKLOG.md F2).
   */
  drawOffer: ChessColor | null;
  /** Кто выиграл. Заполнено только после конца партии. */
  result: "white" | "black" | "draw" | null;
  /** Почему партия кончилась. */
  reason: string | null;
  /** Сколько даётся на ход, как это записано в настройках комнаты. */
  timeControl: TimeControl;
  /**
   * Режим стримера: подсказки гасит клиент. Прятать на сервере тут нечего —
   * позиция и так видна обоим (src/games/chess/docs/BACKLOG.md F1).
   */
  streamerMode: boolean;
  /**
   * На сколько зрители отстают от игроков. Само значение не секрет: секрет —
   * ходы, и их зритель получает позже (src/games/chess/docs/BACKLOG.md F2).
   */
  viewerDelay: ViewerDelay;
  /**
   * Соперник — скрытый пятый уровень.
   *
   * Клиенту это нужно ровно для одного: только в такой партии он сообщает
   * серверу, за какую фигуру игрок взялся. Ни в какой другой этого события не
   * возникает вовсе (src/games/chess/docs/BACKLOG.md D3).
   */
  magnus: boolean;
  /** Только в общем зале: стоит ли этот человек в очереди. */
  queued?: boolean;
  /** Только в общем зале: сводка по залу. */
  lobby?: LobbySummary;
}
