import type { EndReason } from "../engine/outcome";

/**
 * Надбавка к суммарному рейтингу за победу.
 *
 * Суммарный — это рейтинг зала плюс накопленная надбавка, в том числе за победы
 * в приватных комнатах. По нему таблица и сортируется
 * (src/games/chess/docs/BACKLOG.md E2).
 *
 * Смысл потолка в единицу: наигравший тысячу партий со своим попугаем не должен
 * оказаться первым в таблице, играя при этом плохо. Единица против полутора
 * тысяч рейтинга — заметная величина, но не решающая: место определяет умение, а
 * надбавка отражает вложенное время.
 */

/** Больше этого за одну победу не дают. */
export const MAX_BONUS = 1;
/** Ниже этого надбавка не падает, сколько бы партий ни было сыграно. */
export const MIN_BONUS = 0.1;
/** Каждый такой десяток партий с одним соперником стоит одной десятой. */
const PER_STEP = 10;

/**
 * Партия состоялась: не меньше десяти ходов с каждой стороны.
 *
 * Без этого «сдался на втором ходу» становится способом переливать очки.
 */
export const REAL_GAME_PLIES = 20;

/**
 * Рейтинговая партия: не меньше двух ходов с каждой стороны.
 *
 * Порог ниже, чем у надбавки, намеренно: короткая, но настоящая партия рейтинг
 * менять должна — а вот платить за неё надбавкой не за что (E3).
 */
export const RATED_PLIES = 4;

/**
 * Сколько дать за победу над этим соперником.
 *
 * `played` — сколько партий с ним уже сыграно **до** этой. Так повторные партии
 * с одним и тем же человеком дешевеют, и общий зал сам собой оказывается ценнее
 * приватной комнаты: там соперник каждый раз новый.
 */
export function bonusFor(played: number): number {
  const steps = Math.floor(Math.max(0, played) / PER_STEP) / 10;

  return Math.max(MIN_BONUS, MAX_BONUS - steps);
}

/** Победа, за которую вообще положена надбавка. */
export interface Win {
  reason: EndReason;
  /** Сколько полуходов сделано за партию. */
  plies: number;
  /** Соперник — живой человек, а не бот. */
  human: boolean;
}

/**
 * Идёт ли эта победа в зачёт.
 *
 * Победа по времени и по брошенной партии надбавки не даёт: иначе достаточно,
 * чтобы друг просто перестал ходить.
 */
export function counts({ reason, plies, human }: Win): boolean {
  if (!human) return false;
  if (plies < REAL_GAME_PLIES) return false;

  return reason === "checkmate" || reason === "resign";
}
