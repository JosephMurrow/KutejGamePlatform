import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import path from "node:path";
import { describe, it } from "node:test";

/**
 * Выход с экрана ошибки (docs/BACKLOG.md C1).
 *
 * Во вкладке браузера застрять на экране ошибки нельзя: человек тянет страницу
 * вниз или жмёт кнопку в адресной строке. В установленном приложении нет ни
 * жеста обновления, ни строки, ни кнопки браузера — и экран ошибки без своей
 * кнопки означает конец сеанса и удалённую иконку.
 *
 * Отрисовать эти компоненты в тесте нечем: своего рендерера React в проекте
 * нет, а тащить его ради двух файлов незачем. Поэтому проверяется исходник —
 * как и в `src/lib/theme.test.ts`, где так же разбирается `globals.css`.
 * Проверка грубая, но ловит ровно то, что здесь ломается: кнопку, которая
 * называется перезагрузкой, а делает перерисовку.
 */

const ЭКРАНЫ = ["error.tsx", "global-error.tsx"] as const;

function исходник(файл: string): string {
  return readFileSync(path.join(process.cwd(), "src", "app", файл), "utf8");
}

describe("экраны ошибок", () => {
  for (const файл of ЭКРАНЫ) {
    describe(файл, () => {
      const код = исходник(файл);

      it("предлагает настоящую перезагрузку страницей", () => {
        assert.match(
          код,
          /window\.location\.reload\(\)/,
          "нет настоящей перезагрузки — из приложения будет не выйти",
        );
      });

      /**
       * `reset` дешевле и чинит упавший рендер. Убирать его не надо — надо,
       * чтобы он был не единственным.
       */
      it("оставляет и дешёвую попытку через reset", () => {
        assert.match(код, /onClick=\{reset\}/);
      });

      it("перезагрузка висит на кнопке, а не в комментарии", () => {
        assert.match(код, /onClick=\{\(\) => window\.location\.reload\(\)\}/);
      });
    });
  }
});
