/**
 * Полноэкранная раскладка — только в установленном приложении
 * (docs/BACKLOG.md B2).
 *
 * `viewport-fit=cover` — это то, что поднимает `env(safe-area-inset-*)` в
 * полную силу и пускает страницу под вырез и под полоску home. В приложении
 * без него содержимое живёт в прямоугольнике с залитыми полями, то есть
 * выглядит страницей в рамке. А во вкладке Safari он меняет раскладку в
 * альбомной ориентации — и вот этого хозяин просил не делать: приложение
 * поставят не все.
 *
 * Мета-тег вьюпорта один на документ и про `display-mode` ничего не знает,
 * поэтому условие приходится проверять в браузере. Отсюда и эта строчка: она
 * дописывает `viewport-fit=cover`, только если страница уже открыта
 * приложением. Во вкладке она не делает ничего — и это единственное, что
 * важно проверить.
 *
 * Работает до отрисовки: скрипт стоит первым в `<body>`, до содержимого.
 * Асинхронная правка вьюпорта дала бы прыжок раскладки на глазах.
 *
 * `navigator.standalone` — нестандартный признак Safari; на айфоне он и есть
 * единственный надёжный, потому что `display-mode` там поддержан не везде.
 */
export const COVER_IN_STANDALONE = `(function(){try{
var s=window.matchMedia("(display-mode: standalone)").matches||window.navigator.standalone===true;
if(!s)return;
var m=document.querySelector('meta[name="viewport"]');
if(m&&m.content.indexOf("viewport-fit")<0)m.content+=", viewport-fit=cover";
}catch(e){}})();`;
