/**
 * Договор платформы с движком игры.
 *
 * Платформа держит соединение, комнату, состав, чат и рассылку. Всё, что
 * происходит по правилам — фазы, ходы, очки — делает движок, и платформа
 * зовёт его только через этот интерфейс: слова «фаза» она не знает
 * (docs/BACKLOG.md A3).
 *
 * Проверка при добавлении метода: «что сюда положит игра про рисование?».
 * Нет внятного ответа — метод остаётся внутри игры, а не переезжает сюда.
 */

import type { ChatMessagePayload } from "@/shared/protocol";
import type { PrivateRoomInfo } from "@/lib/rooms/private";

/** Кто смотрит: игрок за столом или экран, у которого секретов нет. */
export type GameViewer = { kind: "player"; id: string } | { kind: "screen" };

/**
 * Событие партии: что случилось по правилам. Тип объявляет игра, платформа его
 * не разбирает — она только разносит события подписчикам, чтобы их можно было
 * писать в лог и считать по ним метрики, не заглядывая внутрь игры.
 */
export interface GameRoomEvent {
  type: string;
  [field: string]: unknown;
}

/** Итог действия игрока. */
export interface ActionOutcome {
  accepted: boolean;
  reason?: string;
}

/**
 * Игрок глазами игры. Ник и аватар допишет платформа: их знает она, а не
 * правила.
 */
export interface GamePlayerSlice {
  id: string;
  /** Игровые поля игрока — очки, ход, ставка. Платформа их не читает. */
  extra: Record<string, unknown>;
}

/** Игровая часть снимка комнаты. */
export interface GameRoomSnapshot {
  /**
   * Абсолютное время конца текущей фазы, unix ms. Таймеры серверные, клиент
   * только рисует отсчёт — поэтому дедлайн приходит явным полем.
   */
  deadline: number | null;
  /** Полная длительность фазы: по ней рисуется шкала. */
  phaseDurationMs: number | null;
  /** Состав в игровом порядке. Платформа обрежет и допишет профили. */
  players: GamePlayerSlice[];
  /** Сколько игроков за столом на самом деле. */
  playerCount: number;
  /** Всё прочее, что игра кладёт в снимок. Платформа внутрь не смотрит. */
  extra: Record<string, unknown>;
}

/**
 * Что значит строчка из чужого чата. Платформа читает чат и знает, кто
 * написал; смысл написанного знает игра.
 */
export type ChatIntent =
  | { kind: "act"; event: string; payload: unknown }
  /** Зритель просится за стол. */
  | { kind: "sit" }
  /** Зритель уходит из-за стола. */
  | { kind: "leave" };

/** Кто сидит за столом: столько платформа знает о любом игроке любой игры. */
export interface RoomProfile {
  id: string;
  nickname: string;
  avatarId: number;
  /** Гость: хозяин может его переименовать, не выкидывая из партии. */
  isGuest: boolean;
}

/** Что платформа даёт игре, поднимая комнату. */
export interface GameRoomContext {
  key: string;
  /** Хозяин комнаты; в общем зале — null. */
  ownerId: string | null;
  /** Приватная комната умирает, когда опустеет; общая живёт всегда. */
  isPrivate: boolean;
  /** Настройки партии, как их собрала сама игра. */
  settings: unknown;
  /** Сколько людей подключено сейчас. Вкладки одного человека не в счёт. */
  connections(): number;
  /**
   * Игра посадила за стол своего игрока — бота. Платформа запоминает, как его
   * звать: ник и аватар она дописывает в снимок сама.
   */
  introduce(profile: RoomProfile): void;
  /** Игра увела своего игрока из-за стола. */
  forget(playerId: string): void;
  /**
   * Движок рассказал, что случилось. Платформа разносит это подписчикам:
   * побочные эффекты по своим правилам игра делает сама, но знать о событиях
   * снаружи должно быть можно.
   */
  emitted(events: readonly GameRoomEvent[]): void;
  /**
   * У игры что-то поменялось — разослать снимок и перевести будильник.
   * Зовётся после любого принятого хода, в том числе сделанного изнутри игры:
   * иначе ход бота сдвинул бы дедлайн, а таймер об этом не узнал.
   */
  changed(): void;
}

/**
 * Партия в одной комнате.
 *
 * Платформа создаёт это при подъёме комнаты и гасит при закрытии, а между
 * этим только пересказывает движку, что сделали люди.
 */
export interface GameRoomState {
  /** Игрок сел за стол. */
  join(playerId: string): void;
  /** Игрок ушёл: закрыл все вкладки и не вернулся за отсрочку. */
  leave(playerId: string): void;
  /** Кто сидит за столом. По этому считается заполненность комнаты. */
  seated(): readonly string[];
  /**
   * Когда движок ждёт побудки, unix ms; null — часы стоят.
   *
   * Все таймеры серверные: клиент получает тот же дедлайн в снимке и только
   * рисует по нему отсчёт. Будильник по этому времени заводит платформа.
   */
  deadline(): number | null;
  /**
   * Время вышло — двигай состояние. Что при этом происходит, решают правила:
   * у платитутки сгорает вопрос ведущего, вскрываются ставки или начинается
   * следующий раунд.
   */
  tick(now: number): void;
  /** Действие игрока. Имя события — из протокола игры. */
  act(
    event: string,
    actorId: string,
    payload: unknown,
  ): ActionOutcome | Promise<ActionOutcome>;
  /**
   * Хозяин убирает игрока из партии. Сокет ему рвёт платформа: выгнать из
   * круга мало, иначе человек остался бы в комнате призраком.
   */
  remove(actorId: string, targetId: string): ActionOutcome;
  /** Игровая часть снимка для конкретного зрителя. */
  snapshot(viewer: GameViewer): GameRoomSnapshot;
  /**
   * Что значит строчка из чужого чата — например, из Твича. Платформа читает
   * чат и опознаёт зрителя, а смысл сообщения знает игра: `!500` — это ставка
   * платитутки, а не платформы (docs/BACKLOG.md A1).
   */
  fromChat?(text: string): ChatIntent | null;
  /**
   * Дождаться, пока игра дожуёт свои побочные эффекты — записи в базу и всё,
   * что тянется за ходом. Платформа ждёт этого перед первым снимком: вход
   * может запустить раунд, а подробности подгружаются следующим шагом, и
   * снимок, отправленный в это окно, ушёл бы пустым.
   */
  settled(): Promise<void>;
  /** Погасить таймеры партии. */
  stop(): void;
}

/** Что платформа даёт игре на весь срок жизни процесса. */
export interface GameHost {
  /** Сказать что-нибудь в чат комнаты от имени игрока — например, бота. */
  sendChat(roomKey: string, message: ChatMessagePayload): void;
}

/**
 * Серверная часть игры целиком: она заводит комнаты и живёт, пока живёт
 * процесс. Здесь же боты, мосты и кеши — всё, что у игры своё.
 */
export interface GameServer {
  /** Поднять партию в комнате. */
  createRoom(context: GameRoomContext): Promise<GameRoomState>;
  /** Комнату погасили. */
  closeRoom?(key: string): void;
  /** Остановить всё своё при выключении сервера. */
  stop(): void;
}

/** Как платформа поднимает серверную часть игры. */
export type GameServerFactory = (host: GameHost) => GameServer;

/**
 * Серверная половина договора: всё, что игра даёт процессу, а не браузеру.
 *
 * Живёт отдельно от `GameManifest` намеренно — тот едет в клиентский бандл, и
 * один импорт отсюда утащил бы туда весь серверный хвост.
 */
export interface GameServerManifest {
  /** Тот же код, что и в клиентском манифесте. */
  id: string;
  /**
   * Ключ общего зала. Повторяет клиентский манифест: обе половины берут его
   * из одной константы игры, а держать их вместе нельзя — серверную в браузер
   * не пускаем.
   */
  commonRoomKey: string;
  /** Настройки партии в общем зале: их игра задаёт сама. */
  commonRoomSettings: unknown;
  /**
   * Настройки партии в этой комнате. Игра читает их из своей схемы: платформа
   * не знает, какие у игры настройки, и не хранит их (docs/BACKLOG.md A4).
   */
  loadRoomSettings(room: PrivateRoomInfo): Promise<unknown>;
  /**
   * Комнату создали — игра сохраняет свою часть той же формы. Что в ней за
   * поля, знает только она; платформа передаёт форму как есть.
   */
  saveRoomSettings(roomId: string, form: FormData): Promise<void>;
  /**
   * Какие действия игра слушает в сокете. Платформа их только регистрирует и
   * передаёт движку — что они значат, знает он.
   */
  actions: readonly string[];
  /**
   * Комнату удалили — игра убирает всё, что хранила про неё в базе. Платформа
   * не знает ни одной игровой таблицы и удалять их сама не может.
   */
  dropRoomData(key: string): Promise<void>;
  /** Чем поднять серверную часть игры. */
  createServer: GameServerFactory;
}
