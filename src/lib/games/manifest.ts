import type { ComponentType } from "react";

/**
 * Номера аватаров выше этой границы — служебные: это боты, а не люди.
 * Себе такой аватар выбрать нельзя (см. проверку в lib/auth/actions).
 */
export const BOT_AVATAR_BASE = 1000;

/**
 * Набор аватаров ботов одной игры. Игры будут очень разные, и робот из одной
 * в другой окажется чужим, поэтому набор приносит игра, а платформа только
 * держит за ней поддиапазон номеров (docs/BACKLOG.md D5).
 */
export interface BotAvatarPack {
  /** Первый номер, отданный игре. */
  offset: number;
  /** Сколько номеров занято. */
  count: number;
  /** Чем рисовать. Платформа зовёт, но внутрь не смотрит. */
  Render: ComponentType<{ id: number; size: number; className?: string }>;
}

export interface GameRoutes {
  /** Страница игры: правила и вход за стол. */
  home: string;
  /** Общий зал. */
  play: string;
  /** Создание своей комнаты. */
  newRoom: string;
  /** Рейтинг. */
  leaderboard: string;
}

/**
 * Договор игры с платформой — та его часть, которую видит браузер.
 *
 * Серверное сюда класть нельзя: этот файл едет в клиентский бандл вместе с
 * аватарами, и один импорт движка утащил бы туда весь Prisma. Всё серверное —
 * в `GameServerManifest` (см. engine.ts).
 *
 * Манифест растёт по мере надобности. Поля, которым пока нечего дать —
 * логотип, тема коробки, фавикон — появятся вместе с витриной и оформлением
 * (docs/BACKLOG.md A2, этапы 5–7 в docs/PLAN.md).
 */
export interface GameManifest {
  /** Код игры: им она зовётся в адресах, в базе и в реестре. */
  id: string;
  /** Человеческое название. */
  title: string;
  /** Строчка под названием: чем игра занимается, в одну фразу. */
  tagline: string;
  /** Игра взрослая — метка видна на полке, до входа, а не после. */
  adult: boolean;
  /** Адреса страниц игры. Витрина ведёт на `home`. */
  routes: GameRoutes;
  /**
   * Коробка на витрине. Обязательна: игра без коробки на полку не выходит.
   * Форму даёт платформа (`BoxFrame`), игра — цвета и рисунок крышки; правила
   * и размеры — в docs/BOX.md.
   */
  Box: ComponentType<{ className?: string }>;
  /**
   * Ключ общего зала. Строки в базе нет — общий зал живёт литералом, и за
   * платитуткой он остаётся прежним, потому что за ним лежат живые раунды
   * и очки (docs/BACKLOG.md A4).
   */
  commonRoomKey: string;
  botAvatars: BotAvatarPack;
}
